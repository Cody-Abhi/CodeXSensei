import { formatMinor } from '../../../shared/money';
import type { Currency, Plan } from '../../../shared/types';

export function planToMarkdown(plan: Plan, eventName: string, currency: Currency): string {
  const lines: string[] = [];
  lines.push(`# ${eventName} — Event Plan`);
  lines.push('');
  lines.push(`## Summary`);
  lines.push(plan.summary);
  lines.push('');

  lines.push('## Budget');
  for (const item of plan.budget) {
    lines.push(
      `- **${item.category}**: ${formatMinor(item.amountMinor, currency)} — ${item.rationale}`,
    );
  }
  lines.push('');

  lines.push('## Timeline');
  for (const item of plan.timeline) {
    const status = item.done ? '[x]' : '[ ]';
    lines.push(`- ${status} **${item.title}** (${item.dueDate}) — ${item.phase}`);
  }
  lines.push('');

  lines.push('## Vendors');
  for (const v of plan.vendors) {
    lines.push(`- **${v.name}** (${v.category}) — ${v.status} — ${v.why}`);
  }
  lines.push('');

  lines.push('## Ideas');
  const categories = [...new Set(plan.ideas.map((i) => i.category))];
  for (const cat of categories) {
    lines.push(`### ${cat}`);
    for (const idea of plan.ideas.filter((i) => i.category === cat)) {
      lines.push(`- **${idea.title}**: ${idea.description}`);
    }
  }
  lines.push('');
  lines.push('---');
  lines.push('*Generated by PlanPop*');
  return lines.join('\n');
}

export function downloadJSON(plan: Plan, filename: string): void {
  const json = JSON.stringify(plan, null, 2);
  const blob = new Blob([json], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function copyToClipboard(text: string): Promise<void> {
  return navigator.clipboard.writeText(text);
}
