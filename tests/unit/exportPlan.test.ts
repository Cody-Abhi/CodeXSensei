import { describe, expect, it, vi } from 'vitest';

import {
  copyToClipboard,
  downloadJSON,
  planToMarkdown,
} from '../../src/client/features/plan/exportPlan';
import { buildFallbackPlan } from '../../src/shared/templates';
import type { EventInput } from '../../src/shared/types';

const input: EventInput = {
  type: 'birthday',
  name: 'Test Party',
  date: '2099-06-15',
  city: 'Pune',
  guests: 20,
  budgetMinor: 2_500_000,
  currency: 'INR',
  vibes: [],
  dietary: [],
  notes: '',
};
const plan = buildFallbackPlan(input);

describe('planToMarkdown', () => {
  it('includes the event name as a heading', () => {
    const md = planToMarkdown(plan, 'Test Party', 'INR');
    expect(md).toContain('# Test Party — Event Plan');
  });

  it('includes section headers', () => {
    const md = planToMarkdown(plan, 'Test Party', 'INR');
    expect(md).toContain('## Summary');
    expect(md).toContain('## Budget');
    expect(md).toContain('## Timeline');
    expect(md).toContain('## Vendors');
    expect(md).toContain('## Ideas');
  });

  it('includes the plan summary', () => {
    const md = planToMarkdown(plan, 'Test Party', 'INR');
    expect(md).toContain(plan.summary);
  });

  it('includes budget items', () => {
    const md = planToMarkdown(plan, 'Test Party', 'INR');
    for (const item of plan.budget) {
      expect(md).toContain(item.category);
    }
  });

  it('includes timeline items with done checkboxes', () => {
    const md = planToMarkdown(plan, 'Test Party', 'INR');
    expect(md).toContain('[ ]');
  });

  it('includes vendor names', () => {
    const md = planToMarkdown(plan, 'Test Party', 'INR');
    for (const v of plan.vendors) {
      expect(md).toContain(v.name);
    }
  });

  it('includes ideas grouped by category', () => {
    const md = planToMarkdown(plan, 'Test Party', 'INR');
    const categories = [...new Set(plan.ideas.map((i) => i.category))];
    for (const cat of categories) {
      expect(md).toContain(`### ${cat}`);
    }
  });

  it('marks done timeline items with [x]', () => {
    const modified = {
      ...plan,
      timeline: plan.timeline.map((t, i) => (i === 0 ? { ...t, done: true } : t)),
    };
    const md = planToMarkdown(modified, 'Test', 'INR');
    expect(md).toContain('[x]');
  });

  it('ends with the PlanPop attribution', () => {
    const md = planToMarkdown(plan, 'Test Party', 'INR');
    expect(md).toContain('*Generated by PlanPop*');
  });
});

describe('downloadJSON', () => {
  it('creates and clicks an anchor element to download', () => {
    const revokeObjectURL = vi.spyOn(URL, 'revokeObjectURL').mockReturnValue(undefined);
    const createObjectURL = vi.spyOn(URL, 'createObjectURL').mockReturnValue('blob:test');
    const clickSpy = vi.fn();
    const removeSpy = vi.fn();
    vi.spyOn(document, 'createElement').mockReturnValue({
      set href(_v: string) {},
      set download(_v: string) {},
      click: clickSpy,
      remove: removeSpy,
    } as unknown as HTMLAnchorElement);
    vi.spyOn(document.body, 'appendChild').mockReturnValue(null as unknown as Node);

    downloadJSON(plan, 'test.json');

    expect(createObjectURL).toHaveBeenCalled();
    expect(clickSpy).toHaveBeenCalled();
    expect(removeSpy).toHaveBeenCalled();
    expect(revokeObjectURL).toHaveBeenCalledWith('blob:test');
  });
});

describe('copyToClipboard', () => {
  it('calls navigator.clipboard.writeText', async () => {
    const writeSpy = vi.fn().mockResolvedValue(undefined);
    Object.assign(navigator, { clipboard: { writeText: writeSpy } });
    await copyToClipboard('test text');
    expect(writeSpy).toHaveBeenCalledWith('test text');
  });
});
